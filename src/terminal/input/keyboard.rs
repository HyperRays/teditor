//! Normalized keyboard, text and IME events.

use super::{InputEvent, Modifiers};
pub use winit::event::ElementState;
pub use winit::keyboard::{
    Key, KeyCode, KeyLocation, NamedKey, NativeKey, NativeKeyCode, PhysicalKey,
};

/// Platform-normalized keyboard input. This is also the injection point for hosts
/// other than winit and for tests; never infer `text` from a physical key code.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct KeyInput {
    /// The key's position on the keyboard.
    pub physical_key: PhysicalKey,
    /// What the key means under the current layout.
    pub logical_key: Key,
    /// What the key would mean with no modifiers held.
    pub key_without_modifiers: Option<Key>,
    /// Left, right, numpad or standard.
    pub location: KeyLocation,
    /// Pressed or released.
    pub state: ElementState,
    /// Auto-repeat from holding the key.
    pub repeat: bool,
    /// Generated by the platform, such as when focus returns with the key held.
    pub synthetic: bool,
    /// The text this press produced, if any.
    pub text: Option<String>,
}

impl KeyInput {
    /// Convert a native key event.
    pub fn from_winit(event: &winit::event::KeyEvent, synthetic: bool) -> Self {
        // This extension is available on winit's desktop backends. In particular,
        // it preserves layout-aware shortcut identities when Shift/Option are held.
        #[cfg(any(
            target_os = "windows",
            target_os = "macos",
            target_os = "linux",
            target_os = "freebsd",
            target_os = "dragonfly",
            target_os = "netbsd",
            target_os = "openbsd"
        ))]
        let key_without_modifiers = {
            use winit::platform::modifier_supplement::KeyEventExtModifierSupplement;
            Some(event.key_without_modifiers())
        };
        #[cfg(not(any(
            target_os = "windows",
            target_os = "macos",
            target_os = "linux",
            target_os = "freebsd",
            target_os = "dragonfly",
            target_os = "netbsd",
            target_os = "openbsd"
        )))]
        let key_without_modifiers = None;
        Self {
            physical_key: event.physical_key,
            logical_key: event.logical_key.clone(),
            key_without_modifiers,
            location: event.location,
            state: event.state,
            repeat: event.repeat,
            synthetic,
            text: event.text.as_ref().map(ToString::to_string),
        }
    }
}

/// What a key did.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum KeyState {
    /// It went down.
    Pressed,
    /// It came up.
    Released,
    /// It was held when focus was lost, so no release will arrive.
    Cancelled,
}

/// Key identity and state for shortcuts/navigation. Insert characters only from
/// InputEvent::Text, not from logical_key, which may be a dead key or a shortcut.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct KeyEvent {
    /// The key's position on the keyboard.
    pub physical_key: PhysicalKey,
    /// What the key means under the current layout.
    pub logical_key: Key,
    /// What the key would mean with no modifiers held.
    pub key_without_modifiers: Option<Key>,
    /// Left, right, numpad or standard.
    pub location: KeyLocation,
    /// What the key did.
    pub state: KeyState,
    /// Auto-repeat from holding the key.
    pub repeat: bool,
    /// Generated by the platform rather than typed.
    pub synthetic: bool,
    /// Modifiers held at the time.
    pub modifiers: Modifiers,
    /// An input method composition was running, so this should not act as a shortcut.
    pub composing: bool,
}

impl KeyEvent {
    /// Safe starting point for shortcuts and editing commands. Repeats are allowed;
    /// commands that should run once per press should additionally check !repeat.
    pub fn is_actionable(&self) -> bool {
        self.state == KeyState::Pressed && !self.synthetic && !self.composing
    }
}

/// Where inserted text came from.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum TextSource {
    /// Directly from a key press.
    Keyboard,
    /// Committed by an input method.
    Ime,
}

/// Committed UTF-8 text. A keyboard repeat produces another text event; releases,
/// synthetic focus-restoration presses, and preedit updates never do.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TextInput {
    /// The complete text.
    pub text: String,
    /// Where it came from.
    pub source: TextSource,
    /// Modifiers held at the time.
    pub modifiers: Modifiers,
}

/// Uncommitted text an input method is composing.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Preedit {
    /// The text so far, which must not be inserted into the document.
    pub text: String,
    /// UTF-8 byte offsets, not character/cell indices. None hides the composition
    /// cursor. Both ends are validated as character boundaries; direction is retained.
    pub cursor: Option<(usize, usize)>,
}

/// A change in input method state.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ImeEvent {
    /// An input method became active.
    Enabled,
    /// The composition changed.
    Preedit(Preedit),
    /// Cancel temporary composition without inserting it into the document.
    Cancelled,
    /// The input method was turned off.
    Disabled,
}

/// Cell-aligned editing/caret area converted to physical pixels for the native IME.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ImeCursorArea {
    /// Top left, in physical pixels.
    pub position: [u32; 2],
    /// Size, in physical pixels.
    pub size: [u32; 2],
}

pub(super) struct KeyboardState {
    pressed: Vec<KeyEvent>,
    pub focused: bool,
    pub ime_enabled: bool,
    pub preedit: Option<Preedit>,
}

impl Default for KeyboardState {
    fn default() -> Self {
        Self {
            pressed: Vec::new(),
            focused: true,
            ime_enabled: false,
            preedit: None,
        }
    }
}

impl KeyboardState {
    pub fn is_pressed(&self, key: PhysicalKey) -> bool {
        self.pressed.iter().any(|event| event.physical_key == key)
    }

    pub fn is_composing(&self) -> bool {
        self.preedit.is_some()
    }

    pub fn alt_graph(&self, modifiers: Modifiers) -> bool {
        self.pressed
            .iter()
            .any(|key| key.logical_key == Key::Named(NamedKey::AltGraph))
            || (!cfg!(target_os = "macos")
                && modifiers.control
                && modifiers.alt
                && self.is_pressed(PhysicalKey::Code(KeyCode::AltRight)))
    }

    pub fn handle(&mut self, input: KeyInput, modifiers: &mut Modifiers) -> Vec<InputEvent> {
        if !self.focused && input.state == ElementState::Pressed {
            return Vec::new();
        }
        let existing = self.pressed.iter().position(|key| {
            key.physical_key == input.physical_key && key.location == input.location
        });
        let pressed = input.state == ElementState::Pressed;
        let mut key = KeyEvent {
            physical_key: input.physical_key,
            logical_key: input.logical_key,
            key_without_modifiers: input.key_without_modifiers,
            location: input.location,
            state: if pressed {
                KeyState::Pressed
            } else {
                KeyState::Released
            },
            // Native repeat is authoritative: IMEs can consume releases, so a
            // tracked key alone cannot distinguish a fresh press from a repeat.
            repeat: pressed && input.repeat,
            synthetic: input.synthetic,
            modifiers: *modifiers,
            composing: self.is_composing(),
        };
        if pressed {
            if let Some(index) = existing {
                self.pressed[index] = key.clone();
            } else {
                self.pressed.push(key.clone());
            }
        } else if let Some(index) = existing {
            self.pressed.remove(index);
        }
        modifiers.alt_graph = self.alt_graph(*modifiers);
        key.modifiers = *modifiers;
        let text_allowed = key.is_actionable()
            && !matches!(key.logical_key, Key::Dead(_))
            && !modifiers.super_key
            && (!modifiers.control || modifiers.alt_graph);
        let mut events = vec![InputEvent::Key(key)];
        if text_allowed && let Some(text) = input.text {
            // Enter, Tab, Backspace, Escape, and control chords are key actions.
            // Leave all non-control Unicode intact, including combining marks/ZWJ.
            let text: String = text.chars().filter(|ch| !ch.is_control()).collect();
            if !text.is_empty() {
                events.push(InputEvent::Text(TextInput {
                    text,
                    source: TextSource::Keyboard,
                    modifiers: *modifiers,
                }));
            }
        }
        events
    }

    pub fn ime(&mut self, ime: &winit::event::Ime, modifiers: Modifiers) -> Vec<InputEvent> {
        use winit::event::Ime;
        match ime {
            Ime::Enabled => {
                if self.ime_enabled {
                    return Vec::new();
                }
                self.ime_enabled = true;
                vec![InputEvent::Ime(ImeEvent::Enabled)]
            }
            Ime::Disabled => {
                let mut events = self.cancel_preedit();
                self.ime_enabled = false;
                events.push(InputEvent::Ime(ImeEvent::Disabled));
                events
            }
            Ime::Preedit(text, cursor) if self.focused && self.ime_enabled => {
                let preedit = Preedit {
                    text: text.clone(),
                    cursor: cursor.filter(|&(start, end)| {
                        text.is_char_boundary(start) && text.is_char_boundary(end)
                    }),
                };
                self.preedit = (!text.is_empty()).then(|| preedit.clone());
                vec![InputEvent::Ime(ImeEvent::Preedit(preedit))]
            }
            Ime::Commit(text) if self.focused && self.ime_enabled => {
                let mut events = Vec::new();
                if self.preedit.take().is_some() {
                    events.push(InputEvent::Ime(ImeEvent::Preedit(Preedit {
                        text: String::new(),
                        cursor: None,
                    })));
                }
                // An IME commit is already translated text: do not suppress it
                // because modifiers used to select a candidate are still down.
                if !text.is_empty() {
                    events.push(InputEvent::Text(TextInput {
                        text: text.clone(),
                        source: TextSource::Ime,
                        modifiers,
                    }));
                }
                events
            }
            _ => Vec::new(),
        }
    }

    pub fn cancel(&mut self, modifiers: Modifiers) -> Vec<InputEvent> {
        let mut events: Vec<_> = self
            .pressed
            .drain(..)
            .map(|mut key| {
                key.state = KeyState::Cancelled;
                key.repeat = false;
                key.synthetic = true;
                key.modifiers = modifiers;
                InputEvent::Key(key)
            })
            .collect();
        events.extend(self.cancel_preedit());
        events
    }

    pub fn cancel_preedit(&mut self) -> Vec<InputEvent> {
        if self.preedit.take().is_some() {
            vec![InputEvent::Ime(ImeEvent::Cancelled)]
        } else {
            Vec::new()
        }
    }
}
